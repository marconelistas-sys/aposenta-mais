  assert.equal(await capital.inputValue(), 'no')
  await capital.selectOption('yes')
  await target.waitFor({ state: 'visible' })
  await target.selectOption('finapp:initial_assets:1')
  await editor.getByRole('button', { name: 'Salvar alterações', exact: true }).click()
  assert.equal((await projection())[1].releases[0].amount, 1960)
  await page.evaluate(async () => { const { state } = await import('/src/app/state.js'); state.valuesHidden = true })
