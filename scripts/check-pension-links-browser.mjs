  await editor.getByRole('button', { name: 'Salvar alterações', exact: true }).click()
  await page.reload()
  await page.locator('[data-open-local]').click()
  assert.equal(await page.evaluate(async () => { const { state } = await import('/src/app/state.js'); return state.cashFlow.items[0].pensionInvestmentId }), null)
  const separate = await projection()
  assert.equal(separate[0].releases[0].amount, 960)
  await go('/orcamento?review=budget&id=finapp%3Apension_contributions%3A2&field=pensionInvestmentId')
  await target.selectOption('finapp:initial_assets:1')
