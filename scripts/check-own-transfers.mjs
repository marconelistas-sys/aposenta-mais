import assert from 'node:assert/strict'
export async function checkOwnTransfers(page) {
  await page.evaluate(async () => {
    const { updateCashFlow } = await import('/src/app/state.js')
    const item = (id, type, account, amount, currency, description) => ({ id, type, statementAccount: account, statementImportKey: `reference:${JSON.stringify([account, id])}`, description, statementDescription: description, recordKind: 'actual', imported: true, amount, currency, startDate: '2026-01-10', frequency: 'occasional', categoryId: type === 'income' ? 'other-income' : 'other-expense' })
    updateCashFlow({ ownStatementAccounts: [], items: [item('transfer-out', 'expense', 'TKB:test', 102, 'CHF', 'Wise ref: ABC12345 fee CHF 2.00'), item('transfer-in', 'income', 'BB:test', 620, 'BRL', 'Wise ref: ABC12345'), item('third-party', 'expense', 'TKB:test', 19, 'CHF', 'Wise loja exemplo')] })
  })
  await page.reload()
  await page.locator('[data-open-local]').click()
  await page.locator('a[href="/orcamento?aba=resumo"]').filter({ visible: true }).first().click()
  await page.locator('[data-open-budget-transfers]').click()
  await page.locator('[data-open-budget-transfers]').click()
  const form = page.locator('[data-own-transfers-form]')
  // Transfer details fill the row rather than the 20px import-checkbox column.
  const transferRows = form.locator('.own-transfer-row')
  assert.equal(await transferRows.count(), 3)
  for (const width of [1440, 800, 768, 375, 320]) {
    await page.setViewportSize({ width, height: 950 })
    const layout = await transferRows.first().evaluate(row => {
      const bounds = row.getBoundingClientRect()
      const details = row.querySelector('.own-transfer-row__details').getBoundingClientRect()
      const treatment = row.querySelector('.own-transfer-row__treatment').getBoundingClientRect()
      return { row: bounds.width, details: details.width, treatment: treatment.width, beside: treatment.left >= details.right, below: treatment.top >= details.bottom, fits: row.scrollWidth <= row.clientWidth }
    })
    assert.ok(layout.details >= layout.row * .4, `Transfer details collapsed at ${width}px`)
    assert.ok(layout.fits, `Transfer row overflow at ${width}px`)
    assert.ok(width > 720 ? layout.beside : layout.below, `Transfer columns misplaced at ${width}px`)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Transfer page overflow at ${width}px`)
    await page.screenshot({ path: `/tmp/fin2-own-transfers-${width}.png`, fullPage: true })
  }
  await page.setViewportSize({ width: 1440, height: 950 })
  await form.locator('[name="ownAccount"]').nth(0).check()
  await form.locator('[name="ownAccount"]').nth(1).check()
  await form.locator('[type="submit"]').click()
  assert.match(await form.innerText(), /Conciliada automaticamente/)
  assert.match(await form.innerText(), /6.200000 BRL\/CHF/)
  const totals = await page.evaluate(async () => {
    const { state } = await import('/src/app/state.js')
    const { summarizeCashFlowItems } = await import('/src/domain/cash-flow.js')
    return summarizeCashFlowItems(state.cashFlow, 'CHF', state.exchangeRates, [], new Date('2026-01-15'), 'actual').summary
  })
  assert.equal(totals.occasionalIncome, 0)
  assert.equal(totals.occasionalExpenses, 21)
  await page.reload()
  await page.locator('[data-open-local]').click()
  await page.locator('a[href="/orcamento?aba=resumo"]').filter({ visible: true }).first().click()
  await page.locator('[data-open-budget-transfers]').click()
  assert.match(await form.innerText(), /Conciliada automaticamente/)
  await form.locator('[name="decision:third-party"]').selectOption('payment')
  await form.locator('[type="submit"]').click()
  const reimport = await page.evaluate(async () => {
    const { state, upsertStatementItems } = await import('/src/app/state.js')
    const ids = state.cashFlow.items.map(item => item.id)
    const incoming = state.cashFlow.items.map(item => { const row = { ...item }; delete row.transferDecision; return row })
    const result = upsertStatementItems(incoming)
    return { result, sameIds: JSON.stringify(ids) === JSON.stringify(state.cashFlow.items.map(item => item.id)), decision: state.cashFlow.items.find(item => item.id === 'third-party').transferDecision, matched: state.cashFlow.items.filter(item => item.transferMatch).length }
  })
  assert.deepEqual(reimport, { result: { added: 0, updated: 3 }, sameIds: true, decision: 'payment', matched: 2 })
  await form.locator('[name="decision:transfer-out"]').selectOption('payment')
  await form.locator('[type="submit"]').click()
  assert.doesNotMatch(await form.innerText(), /Conciliada automaticamente/)
  await form.locator('[name="decision:transfer-out"]').selectOption('own')
  await form.locator('[type="submit"]').click()
  assert.match(await form.innerText(), /Conciliada automaticamente/)
  await page.setViewportSize({ width: 375, height: 812 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  await page.evaluate(async () => {
    const { updateCashFlow } = await import('/src/app/state.js')
    updateCashFlow({ referenceMonth: '2026-01', ownStatementAccounts: [], items: [{ id: 'unrecognized', type: 'expense', categoryId: 'other-expense', description: 'Movimento bancário 123', amount: 100, currency: 'CHF', startDate: '2026-01-10', endDate: '2026-01-10', frequency: 'occasional', recordKind: 'actual', imported: true, statementImportKey: 'reference:["","unknown-123"]' }] })
  })
  await page.reload()
  await page.locator('[data-open-local]').click()
  await page.locator('a[href="/orcamento?aba=resumo"]').filter({ visible: true }).first().click()
  await page.locator('[data-open-budget-transfers]').click()
  assert.equal(await form.locator('[name="decision:unrecognized"]').count(), 1)
  await page.locator('[data-page-tab="orcamento:lancamentos"]').click()
  await page.locator('[data-edit-cash-item="unrecognized"]').click()
  const editor = page.locator('[data-cash-item-edit-form]')
  await editor.locator('[name="transferDecision"]').selectOption('own')
  await editor.locator('[type="submit"]').click()
  assert.match(await page.locator('.cash-item').filter({ hasText: 'Movimento bancário 123' }).innerText(), /Transferência entre minhas contas.*Fora do orçamento/s)
  const verified = await page.evaluate(async () => {
    const { state, upsertStatementItems } = await import('/src/app/state.js')
    const { buildBudgetYear } = await import('/src/domain/budget-overview.js')
    const incoming = { ...state.cashFlow.items[0] }
    delete incoming.transferDecision
    const result = upsertStatementItems([incoming])
    return { result, decision: state.cashFlow.items[0].transferDecision, expenses: buildBudgetYear(state, 2026).annual.actual.expenses }
  })
  assert.deepEqual(verified, { result: { added: 0, updated: 1 }, decision: 'own', expenses: 0 })
  await page.reload()
  await page.locator('[data-open-local]').click()
  await page.locator('a[href="/orcamento?aba=resumo"]').filter({ visible: true }).first().click()
  await page.locator('[data-page-tab="orcamento:lancamentos"]').click()
  await page.locator('[data-edit-cash-item="unrecognized"]').click()
  assert.equal(await editor.locator('[name="transferDecision"]').inputValue(), 'own')
  await editor.locator('[name="transferDecision"]').selectOption('payment')
  await editor.locator('[type="submit"]').click()
  const restored = await page.evaluate(async () => {
    const { state } = await import('/src/app/state.js')
    const { transferBudgetAmount } = await import('/src/domain/own-transfers.js')
    return transferBudgetAmount(state.cashFlow.items[0])
  })
  assert.equal(restored, 100)
  await page.locator('[data-open-budget-transfers]').click()
  await form.locator('[name="decision:unrecognized"]').selectOption('own')
  await form.locator('[type="submit"]').click()
  assert.match(await form.innerText(), /Transferência confirmada por você, principal fora do orçamento/)
  console.log('Transferências validadas no navegador: titularidade, câmbio, tarifas, terceiros, reload e reimportação.')
}
